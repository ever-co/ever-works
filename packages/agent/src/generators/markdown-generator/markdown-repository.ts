import * as path from 'node:path';
import * as fs from 'node:fs/promises';

// Security (path traversal): a caller-supplied `slug` is interpolated into a
// filename under `details/`. `path.basename` already drops directory parts, but
// it has platform-dependent edge cases and would happily accept OS-reserved
// names like `.`/`..`, so we additionally require a strict allowlist matching
// the `slugifyText` output charset ([A-Za-z0-9_-]) before any path is built.
// Mirrors `DataRepository.confineSlugPath` / `GitHubSyncService.safeSlugDir`.
const SAFE_SLUG_PATTERN = /^[a-zA-Z0-9_-]+$/;

/**
 * Folder (at the repository root) that holds one Markdown page per category
 * when a README is too large for GitHub to render in one file. See
 * `buildSplitReadme` in `readme-builder.ts`.
 */
export const CATEGORY_PAGES_DIR = 'categories';

/**
 * First line of every generated category page. Stale-page cleanup only ever
 * deletes files that start with it, so a hand-written `categories/*.md` (or,
 * in single-repository storage, anything else that lives in a `categories/`
 * folder) is never touched.
 */
export const CATEGORY_PAGE_MARKER = '<!-- Generated by Ever Works: category page. Do not edit. -->';

// Same idea as SAFE_SLUG_PATTERN, for the generated `<category>[--page-N].md`
// names (`toCategoryFileSlug` only emits `[a-z0-9-]`).
const CATEGORY_PAGE_FILE_PATTERN = /^[a-z0-9][a-z0-9-]*\.md$/;

export class MarkdownRepository {
    private readonly detailsPath: string;
    private readonly categoriesPath: string;

    /**
     * Tracks how many filesystem writes / removes this instance has
     * performed since construction. Surfaced by {@link getWriteCount}
     * so the EW-628 data-repo sync entry can populate the
     * `filesChanged` activity-feed stat without a separate
     * `git diff` call. Reset implicitly because the instance lives
     * for a single sync run.
     */
    private writeCount = 0;

    constructor(public readonly dir: string) {
        /*
         *   File structure:
         *      - README.md
         *      - details/
         *          - item1.md
         *          - item2.md
         *          - ...
         *          - itemN.md
         *      - categories/        (only when the README is split, see CATEGORY_PAGES_DIR)
         *          - category1.md
         *          - ...
         */
        this.detailsPath = path.join(dir, 'details');
        this.categoriesPath = path.join(dir, CATEGORY_PAGES_DIR);
    }

    async cleanup() {
        await fs.rm(this.dir, { recursive: true, force: true });
    }

    /**
     * Remove all files except allowlisted ones
     * and ensure all needed works exist
     */
    async resetFiles() {
        const files = await fs.readdir(this.dir);
        const allowlist = ['.git', '.gitignore', '.github', '.vscode', '.env', '.nvmrc'];

        for (const file of files) {
            if (allowlist.includes(file) || file.startsWith('.git')) {
                continue;
            }

            await fs.rm(path.join(this.dir, file), { recursive: true, force: true });
            this.writeCount += 1;
        }

        await this.ensureWorksExist();
    }

    async ensureWorksExist() {
        await fs.mkdir(this.detailsPath, { recursive: true });
    }

    async writeReadme(content: string) {
        const filename = path.join(this.dir, 'README.md');
        await fs.writeFile(filename, content, 'utf-8');
        this.writeCount += 1;
    }

    /**
     * Resolve a slug to a `<slug>.md` filename under `detailsPath`, rejecting
     * anything that is not a strict `[A-Za-z0-9_-]+` token or that would escape
     * `detailsPath` once resolved (e.g. `../../etc/passwd`). Throws on a hostile
     * slug BEFORE the path reaches any `fs.writeFile`/`fs.rm` sink, so the
     * traversal never performs an arbitrary file write/delete. Legitimate slugs
     * are `slugifyText` output ([a-z0-9_-]) and pass through unchanged.
     */
    private detailFilePath(slug: string): string {
        const safeName = path.basename(slug);
        // Reject empty results and anything outside the slug allowlist before
        // building a path — defends against platform-dependent `basename`
        // behaviour and OS-reserved names (`.`, `..`, etc.).
        if (!safeName || safeName !== slug || !SAFE_SLUG_PATTERN.test(safeName)) {
            throw new Error(`Invalid slug: ${slug}`);
        }
        const filename = path.join(this.detailsPath, `${safeName}.md`);
        // Belt-and-suspenders containment check: the resolved file must stay
        // strictly under the resolved details directory.
        const resolvedRoot = path.resolve(this.detailsPath);
        const resolvedChild = path.resolve(filename);
        if (!resolvedChild.startsWith(resolvedRoot + path.sep)) {
            throw new Error(`Invalid slug: ${slug}`);
        }
        return filename;
    }

    async writeDetails(slug: string, content: string) {
        const filename = this.detailFilePath(slug);
        await fs.writeFile(filename, content, 'utf-8');
        this.writeCount += 1;
    }

    async removeDetails(slug: string) {
        const filename = this.detailFilePath(slug);
        await fs.rm(filename, { force: true });
        this.writeCount += 1;
    }

    async writeLicense(content: string) {
        const filepath = path.join(this.dir, 'LICENSE.md');
        await fs.writeFile(filepath, content, 'utf-8');
        this.writeCount += 1;
    }

    /**
     * Resolve a generated category page name (`<slug>.md` / `<slug>--page-N.md`)
     * to a path under `categories/`, rejecting anything else before it reaches
     * a filesystem sink. Same containment rules as {@link detailFilePath}.
     */
    private categoryPageFilePath(fileName: string): string {
        if (
            typeof fileName !== 'string' ||
            path.basename(fileName) !== fileName ||
            !CATEGORY_PAGE_FILE_PATTERN.test(fileName)
        ) {
            throw new Error(`Invalid category page name: ${fileName}`);
        }
        const filename = path.join(this.categoriesPath, fileName);
        const resolvedRoot = path.resolve(this.categoriesPath);
        if (!path.resolve(filename).startsWith(resolvedRoot + path.sep)) {
            throw new Error(`Invalid category page name: ${fileName}`);
        }
        return filename;
    }

    /**
     * Security (link escape): a checkout can carry a committed symlink, which
     * isomorphic-git checks out as a real one. Never write through a linked
     * `categories/` folder, and replace a linked page file instead of writing
     * through it to wherever it points.
     */
    private async assertCategoriesDirIsReal(): Promise<void> {
        const stat = await fs.lstat(this.categoriesPath);
        if (stat.isSymbolicLink() || !stat.isDirectory()) {
            throw new Error(
                `Refusing to write category pages: ${CATEGORY_PAGES_DIR}/ is not a folder`,
            );
        }
    }

    async writeCategoryPage(fileName: string, content: string) {
        const filename = this.categoryPageFilePath(fileName);
        await fs.mkdir(this.categoriesPath, { recursive: true });
        await this.assertCategoriesDirIsReal();

        const existing = await fs.lstat(filename).catch((err: NodeJS.ErrnoException) => {
            if (err?.code === 'ENOENT') {
                return null;
            }
            throw err;
        });
        if (existing && !existing.isFile()) {
            // A link (or anything that is not a plain file) in our own
            // generated slot: remove the entry itself, not its target.
            await fs.rm(filename, { force: true });
        }

        await fs.writeFile(filename, content, 'utf-8');
        this.writeCount += 1;
    }

    /**
     * Delete generated category pages that are not in `keep` — pages of
     * categories that no longer exist, extra `--page-N` files of a category
     * that shrank, or every page once the README fits in one file again.
     *
     * Only plain `.md` files that start with {@link CATEGORY_PAGE_MARKER} are
     * removed; anything else in `categories/` is left alone. The folder itself
     * is removed when it ends up empty (an empty `categories/` folder would
     * make `DataRepository` look for `categories/categories.yml` if this
     * checkout is also the data repository).
     *
     * @returns the number of files removed
     */
    async removeStaleCategoryPages(keep: ReadonlySet<string> = new Set()): Promise<number> {
        try {
            const stat = await fs.lstat(this.categoriesPath);
            if (stat.isSymbolicLink() || !stat.isDirectory()) {
                return 0;
            }
        } catch (err) {
            if ((err as NodeJS.ErrnoException | undefined)?.code === 'ENOENT') {
                return 0;
            }
            throw err;
        }

        const entries = await fs.readdir(this.categoriesPath, { withFileTypes: true });
        let removed = 0;

        for (const entry of entries) {
            if (
                !entry.isFile() ||
                keep.has(entry.name) ||
                !CATEGORY_PAGE_FILE_PATTERN.test(entry.name)
            ) {
                continue;
            }

            const filename = this.categoryPageFilePath(entry.name);
            const content = await fs.readFile(filename, 'utf-8');
            if (!content.startsWith(CATEGORY_PAGE_MARKER)) {
                continue;
            }

            await fs.rm(filename, { force: true });
            removed += 1;
            this.writeCount += 1;
        }

        if (removed === entries.length) {
            await fs.rmdir(this.categoriesPath).catch(() => undefined);
        }

        return removed;
    }

    /**
     * Number of writes (writeReadme / writeDetails / writeLicense /
     * writeCategoryPage / removeDetails / removed stale category pages /
     * resetFiles entries) this instance has performed.
     * Used by EW-628 `syncFromDataRepo` to populate
     * `DataSyncSuccessStats.filesChanged` so the activity feed renders
     * an accurate count without an extra `git diff` round-trip.
     */
    getWriteCount(): number {
        return this.writeCount;
    }
}
